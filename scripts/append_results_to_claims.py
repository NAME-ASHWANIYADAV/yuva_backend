"""Append the measured experiment and safety-sweep numbers to CLAIMS.md (idempotent: replaces the generated block)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

START = "<!-- generated-results:start -->"
END = "<!-- generated-results:end -->"


def fmt(x, nd=0):
    try:
        return f"{float(x):,.{nd}f}"
    except (TypeError, ValueError):
        return "n/a"


def main() -> int:
    exp_path = ROOT / "results" / "experiments" / "summary.json"
    sweep_path = ROOT / "results" / "safety" / "sweep.json"
    lines = [START, "", "### Measured on this machine (generated by `scripts/append_results_to_claims.py`)", ""]
    if exp_path.exists():
        s = json.loads(exp_path.read_text(encoding="utf-8"))
        variants = s.get("variants", [])
        met = s.get("metrics", {})
        abl = s.get("ablation", {})
        lines.append(f"**Experiments** (`results/experiments/`): years {s.get('years')}, {s.get('n_days')} real weather days, "
                     f"{s.get('n_scenarios')} scenarios; status counts of the full system: `{s.get('status_counts')}`; "
                     f"certified plans with verifier violations: **{s.get('certified_plans_with_violations')}**.")
        lines.append("")
        lines.append("| variant | import kWh/day, median (P10–P90) | solar used % of PV, median | PT-2 peak % of rating, median | max DT hot-spot °C, median | DT ageing h/day, median | verify-ok % | median solve s |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for v in variants:
            imp = met.get("import_kwh", {}).get(v, {}); su = met.get("solar_used_frac_of_pv", {}).get(v, {})
            pt = met.get("pt2_max_loading_frac", {}).get(v, {}); hot = met.get("dt_max_hot_spot_c", {}).get(v, {})
            age = met.get("dt_ageing_hours_total", {}).get(v, {}); a = abl.get(v, {})
            lines.append(f"| {v} | {fmt(imp.get('median'))} ({fmt(imp.get('p10'))}–{fmt(imp.get('p90'))}) | "
                         f"{fmt(100 * (su.get('median') or 0), 1)} | {fmt(100 * (pt.get('median') or 0), 0)} | {fmt(hot.get('median'), 1)} | "
                         f"{fmt(age.get('median'), 1)} | {fmt(a.get('verify_ok_%'), 0)} | {fmt(a.get('median_solve_s'), 1)} |")
        d = s.get("paired_delta_import_kwh", {}); ag = s.get("paired_delta_ageing_hours", {})
        lines.append("")
        lines.append(f"Paired per-scenario delta (sunflow_full − published timetable): import {fmt(d.get('median'))} kWh/day median "
                     f"(P10 {fmt(d.get('p10'))}, P90 {fmt(d.get('p90'))}); DT ageing {fmt(ag.get('median'), 2)} h/day median "
                     f"(P10 {fmt(ag.get('p10'), 2)}, P90 {fmt(ag.get('p90'), 2)}). A negative number means SUNFLOW is lower.")
        lines.append("")
        lines.append("Distributions over scenarios, MODELLED on the synthetic Lamjana feeder with real weather; the published-timetable row is the same "
                     "scenarios replayed with MSEDCL's Annexure-A slots (its verify-ok % shows how often today's practice would pass the "
                     "pessimistic check). Import includes night-compensation energy. No single headline percentage is claimed.")
    else:
        lines.append("Experiments: `results/experiments/summary.json` not found (run `scripts/run_experiments.py`).")
    lines.append("")
    if sweep_path.exists():
        w = json.loads(sweep_path.read_text(encoding="utf-8"))
        lines.append(f"**Safety sweep** (`results/safety/sweep.json`): {w.get('n')} seeded random scenarios (seed {w.get('seed')}; participation "
                     f"0.5–1.0, thermal ±30 %, ambient −2…+6 °C, random DT failures and feeder outages, random irrigation needs); status counts "
                     f"`{w.get('status_counts')}`; certified plans with verifier violations: **{w.get('certified_plans_with_violations')}**; "
                     f"median solve {fmt(w.get('median_solve_s'), 1)} s, P90 {fmt(w.get('p90_solve_s'), 1)} s; wall time {fmt(w.get('elapsed_s'))} s.")
    else:
        lines.append("Safety sweep: `results/safety/sweep.json` not found (run `scripts/safety_sweep.py`).")
    lines += ["", END]
    block = "\n".join(lines)
    claims = ROOT / "CLAIMS.md"
    text = claims.read_text(encoding="utf-8")
    if START in text and END in text:
        pre, rest = text.split(START, 1)
        _, post = rest.split(END, 1)
        text = pre + block + post
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    claims.write_text(text, encoding="utf-8")
    sys.stdout.buffer.write((block + "\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
